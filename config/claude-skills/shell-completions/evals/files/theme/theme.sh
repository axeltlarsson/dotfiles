# theme — switch the terminal stack between Rosé Pine main (dark) and dawn (light).
#
# The macOS system appearance is the single source of truth. Ghostty follows it
# natively (`theme = "light:...,dark:..."`), as do bat and yazi, and anything
# configured with ANSI palette slots (fzf, the pure prompt, the tmux status
# line). This script sets the OS appearance and then nudges the three stragglers
# that can't follow on their own: delta, k9s and running neovim instances.
#
# Usage:
#   theme                  print "light" or "dark"
#   theme light | dark     pin the macOS appearance, then sync
#   theme toggle           flip the macOS appearance, then sync
#   theme auto             hand appearance back to macOS's sunrise/sunset schedule
#   theme sync [--force]   re-apply the current appearance without changing it

shopt -s nullglob

readonly DEFAULTS=/usr/bin/defaults
readonly OSASCRIPT=/usr/bin/osascript

state_dir="${XDG_STATE_HOME:-$HOME/.local/state}/theme"
config_home="${XDG_CONFIG_HOME:-$HOME/.config}"
state_file="$state_dir/appearance"
delta_config="$config_home/git/theme.gitconfig"
k9s_skin="$config_home/k9s/skins/current.yaml"

# Every trigger throws stderr away — tmux run-shell, neovim's vim.system, and
# launchd — so anything the user needs to see also has to go through tmux.
notify() {
  echo "theme: $1" >&2
  tmux display-message -d 5000 "theme: $1" 2>/dev/null || true
}

# --- reading and writing the macOS appearance ---------------------------------

current_appearance() {
  if [[ "$("$DEFAULTS" read -g AppleInterfaceStyle 2>/dev/null)" == "Dark" ]]; then
    echo dark
  else
    echo light
  fi
}

# Pinning has to turn off macOS's automatic light/dark schedule, or the choice
# gets silently reverted at the next sunrise/sunset. `theme auto` puts it back.
set_auto_switching() {
  "$DEFAULTS" write -g AppleInterfaceStyleSwitchesAutomatically -bool "$1"
}

# Needs Automation access to System Events. macOS prompts once per calling app,
# and the caller differs per entry point: the tmux server for prefix + T, neovim
# for <Leader>tt, the terminal for an interactive shell.
set_appearance() {
  local dark_mode=false
  [[ $1 == dark ]] && dark_mode=true
  set_auto_switching false
  if ! "$OSASCRIPT" -e \
    "tell application \"System Events\" to tell appearance preferences to set dark mode to $dark_mode" \
    >/dev/null 2>&1; then
    notify "couldn't set the appearance — the calling app needs Automation access to System Events (System Settings > Privacy & Security > Automation)"
    return 1
  fi
}

# --- followers ----------------------------------------------------------------

# delta reads git config on every invocation, so an include file is picked up by
# shells that are already open. Referenced from config/git.nix.
sync_delta() {
  local theme=$1 light=false
  [[ $theme == *dawn ]] && light=true
  mkdir -p "${delta_config%/*}"
  cat >"$delta_config" <<EOF
# Generated by \`theme sync\` — do not edit.
[delta]
	light = $light
	syntax-theme = $theme
EOF
}

# k9s only reads its skin at startup; keep a symlink it can point at.
sync_k9s() {
  local theme=$1
  [[ -d ${k9s_skin%/*} ]] || return 0
  ln -sfn "$theme.yaml" "$k9s_skin"
}

# Running neovim instances, via the RPC sockets under stdpath("run"). Setting
# 'background' reloads the colorscheme, which re-resolves rose-pine's
# variant = "auto" to dawn or main.
#
# The timeout matters: --remote-expr against a suspended (Ctrl-Z) or otherwise
# blocked nvim never returns, which would wedge the launchd agent — launchd
# won't start a second instance of a job that is still running.
sync_nvim() {
  local bg=$1 root sock roots=("${TMPDIR:-/tmp}")
  # A launchd agent's TMPDIR need not match the shell's, so check /tmp as well.
  [[ ${roots[0]} == /tmp ]] || roots+=(/tmp)
  for root in "${roots[@]}"; do
    # Normally nvim.$USER/<random>/nvim.<pid>.<n>; neovim falls back to
    # nvim.<random>/nvim.<pid>.<n> when it can't own the nvim.$USER dir.
    for sock in "$root"/nvim.*/*/nvim.* "$root"/nvim.*/nvim.*; do
      [[ -S $sock ]] || continue
      timeout 2 nvim --server "$sock" \
        --remote-expr "execute('set background=$bg')" &>/dev/null || true
    done
  done
}

# $1: --force to also push to running neovim even when nothing changed.
# $2: the appearance to apply; read from macOS when empty. Callers that just set
#     it pass it through, because cfprefsd may not have observed the write yet.
apply() {
  local force=$1 appearance=${2:-} theme prev=
  [[ -n $appearance ]] || appearance="$(current_appearance)"

  if [[ $appearance == dark ]]; then
    theme=rose-pine
  else
    theme=rose-pine-dawn
  fi

  # Regenerating these is two cheap file operations, so do it unconditionally:
  # the state file outlives reboots, so anything conditional on "did the
  # appearance change" would never restore an output that went missing — and
  # k9s.ui.skin = "current" would then point at nothing indefinitely.
  sync_delta "$theme"
  sync_k9s "$theme"

  [[ -r $state_file ]] && read -r prev <"$state_file"
  mkdir -p "$state_dir"
  # Write atomically — a reader must never see the truncated file.
  printf '%s\n' "$appearance" >"$state_file.tmp"
  mv -f "$state_file.tmp" "$state_file"

  # The only expensive follower (a process spawn per live instance), so skip it
  # when the appearance hasn't actually moved.
  if [[ $force == --force || $prev != "$appearance" ]]; then
    sync_nvim "$appearance"
  fi
}

# --- entry point --------------------------------------------------------------

case "${1:-}" in
"")
  current_appearance
  ;;
light | dark)
  set_appearance "$1"
  apply --force "$1"
  ;;
toggle)
  if [[ "$(current_appearance)" == dark ]]; then
    set_appearance light
    apply --force light
  else
    set_appearance dark
    apply --force dark
  fi
  ;;
auto)
  set_auto_switching true
  apply --force
  ;;
sync)
  apply "${2:-}"
  ;;
*)
  echo "usage: theme [light|dark|toggle|auto|sync [--force]]" >&2
  exit 2
  ;;
esac
